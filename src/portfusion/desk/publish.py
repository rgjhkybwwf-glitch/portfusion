"""PUBLISH THE HOSTED DESK — `portfusion desk --publish`, and only when the owner runs it.

    portfusion desk --publish      # writes the deploy repository's clone, commits, pushes

WHAT IT DOES. It writes the shell (`desk/bundle.py`) and its Netlify settings into the clone of
the deploy-only repository, the book's `deploy_repo` setting, commits, and pushes `main`. Netlify deploys from
that repository and from nothing else, so it never sees this one. Nothing goes online between
publishes.

EVERYTHING IN THAT REPOSITORY IS WRITTEN HERE. The headers, the redirects, the build settings,
the README and the check that runs on Netlify are all generated, and `verify.py` refuses a
deploy whose files differ from the manifest in `version.json`. A hand edit there fails the
deploy; the desk is changed here and published again.

IT REFUSES rather than guessing. The book must name its deploy repository, a clone apart from
the book, the app, the checkout and the home folder, holding only what a publish wrote. This checkout must be on `main`, clean and pushed, so the commit
a publish names exists on GitHub. The tunnel must be up, because the redirects are written to it.
And this Mac must hold the proxy secret (`desk/auth.py:PROXY_SECRET`): the redirects ask Netlify
to sign with its copy, and a door that cannot check the signature refuses everything.
And the bundle may carry nothing from the record and no credential: the same scan
`tests/desk/test_bundle.py` makes, and every credential in the book's folder (`secret_scan.py`).

THE HEADER'S "hosted" SIGNAL is `status()`: the tunnel, and the published version against the
version on disk, read locally with no network call.
"""
from __future__ import annotations

import datetime as _dt
import hashlib
import json
import pathlib
import re
import shutil
import subprocess
import time

from portfusion import brand
from portfusion.desk import auth, bundle
from portfusion.log import log
from portfusion.record import schema

#: The clone of the deploy-only repository, the book's `deploy_repo` (a leading `~` is the home
#: folder); None when the book names none. Outside this one, so nothing here can be published by
#: accident and nothing there can reach this repository's history.
_DEPLOY = dict(schema.load("settings")).get("deploy_repo")
DEPLOY: pathlib.Path | None = pathlib.Path(_DEPLOY).expanduser() if _DEPLOY else None

#: Where Homebrew and the Tailscale app put the command line. A desk started by launchd has a short
#: PATH, so the command is looked for here as well as on it.
TAILSCALE = ("/opt/homebrew/bin/tailscale", "/usr/local/bin/tailscale",
             "/Applications/Tailscale.app/Contents/MacOS/Tailscale")

#: How long the header trusts one reading of the tunnel, so a tab switch does not ask each time.
TUNNEL_CACHE = 30


class Refused(Exception):
    """A publish that did not happen, and why."""


# =================================================================================================
# THE FILES
# =================================================================================================

def _netlify(tunnel: str) -> str:
    """The build settings, and the hosted page's /api and /auth proxied to the tunnel, so the
    browser sees one origin. SIGNED: Netlify signs every proxied request with the secret in the
    named environment variable, and the door refuses any request it did not sign. Netlify signs
    only redirects written here, never in `_redirects`, so there is no `_redirects` file."""
    rules = "".join(f"""
[[redirects]]
  from = "/{path}/*"
  to = "{tunnel}/{path}/:splat"
  status = 200
  signed = "{auth.PROXY_SECRET_ENV}"
""" for path in ("api", "auth"))
    return _NETLIFY + rules


#: Every file is sent with the shell's own headers (`bundle.SHELL_HEADERS`), and nothing indexes it.
#: The manifest is named as what it is: Netlify has no type for .webmanifest and sends a binary
#: blob, which a browser may decline to read as a manifest.
_HEADERS = "/*\n" + "".join(f"  {k}: {v}\n" for k, v in bundle.SHELL_HEADERS.items()) + """\
  X-Robots-Tag: noindex
/
  Cache-Control: no-store
/index.html
  Cache-Control: no-store
/manifest.webmanifest
  Content-Type: application/manifest+json
"""

#: WHAT A CRAWLER MAY FETCH: the shell, so it reads the `X-Robots-Tag: noindex` every response
#: carries, and never /api or /auth, the tunnel to the Mac. Disallowing everything would hide that
#: noindex: a crawler reads a rule only on a page it may fetch, and a site that links here could
#: still get the address listed with no page behind it.
_ROBOTS = "User-agent: *\nDisallow: /api/\nDisallow: /auth/\n"

_NETLIFY = """# GENERATED by PortFusion's `portfusion desk --publish`. Never edit here.
[build]
  publish = "bundle"
  command = "python3 verify.py"
"""

_README = """# The hosted desk — {name}

The hosted desk, as published. **Every file here is generated** by `portfusion desk --publish`,
run in the book's folder, from PortFusion's one copy of the desk's screen. `verify.py` runs as
Netlify's build and refuses a deploy if any file was edited here: change the desk there, then
publish again.
"""

_VERIFY = '''"""Refuse a deploy whose files are not the ones `portfusion desk --publish` wrote. GENERATED."""
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
manifest = json.loads((ROOT / "version.json").read_text())
have = {p.relative_to(ROOT).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
        for p in ROOT.rglob("*") if p.is_file() and ".git" not in p.relative_to(ROOT).parts
        and p.name != "version.json"}
if have != manifest["files"]:
    for name in sorted(set(have) | set(manifest["files"])):
        if have.get(name) != manifest["files"].get(name):
            print(f"refused: {name} is not the file the publish wrote")
    sys.exit(1)
print(f"verified {len(have)} files, desk version {manifest['version']}")
'''


def files(tunnel: str) -> dict[str, bytes]:
    """Every file the deploy repository holds but `version.json`, keyed by its path there."""
    out = {f"bundle{'/index.html' if url == '/' else url}": body
           for url, body in bundle.files().items()}
    out.update({"bundle/_headers": _HEADERS.encode(),
                "bundle/robots.txt": _ROBOTS.encode(),
                "netlify.toml": _netlify(tunnel).encode(), "verify.py": _VERIFY.encode(),
                "README.md": _README.format(name=brand.NAME).encode()})
    return out


def manifest(tree: dict[str, bytes], source: str, now: _dt.datetime | None = None) -> dict:
    """What was published: the bundle's version, the PortFusion release that made it (`code`),
    the book's commit whose figures it serves (`source`), when, and every file's hash."""
    from portfusion import about
    now = now or _dt.datetime.now(_dt.timezone.utc)
    return {"version": bundle.version(), "code": about.release(), "source": source,
            "published": now.replace(microsecond=0).isoformat(),
            "files": {p: hashlib.sha256(b).hexdigest() for p, b in sorted(tree.items())}}


# =================================================================================================
# WHAT MAY NOT GO OUT
# =================================================================================================

def record_values() -> set[str]:
    """Accounts, holders, account numbers, tickers and companies — read through the record's own
    door. None of them may appear in a file that is readable before the hosted sign-in."""

    def column(table, name):
        position = schema.TABLES[table].header.index(name)
        return {str(row[position]).strip() for row in schema.load(table) if row[position]}

    return (column("accounts", "account") | column("accounts", "holder")
            | column("accounts", "number") | column("securities", "ticker")
            | column("securities", "company") | column("buys", "ticker"))


#: A record value this short is an ordinary word in the shell's own prose — a ticker like `ON`
#: would match the page's comments, so a book holding one could never publish. It is looked for
#: outside the comments only, and a single character not at all: it names nothing.
SHORT_VALUE = 3


def _outside_comments(text: str) -> str:
    """The text with its comments taken out: `/* */`, `<!-- -->`, and `//` to the end of a line
    where no `:` or quote stands before it, so a URL keeps its `//`."""
    text = re.sub(r"/\*.*?\*/|<!--.*?-->", " ", text, flags=re.S)
    return re.sub(r"(?m)(^|[^:\"'\\])//.*$", r"\1", text)


def leaks(tree: dict[str, bytes]) -> list[str]:
    """Each text file's record values, matched as whole words, and every credential in the book's
    folder or key-shaped string (`secret_scan.py`).

    A COMMENT IS PUBLISHED TOO: the shell is served whole before the sign-in, so a value longer
    than `SHORT_VALUE` is looked for in every line of it. Shorter ones are looked for outside the
    comments, and a single character is not looked for."""
    values = sorted(v for v in record_values() if len(v) > 1)
    found = []
    for path, body in sorted(tree.items()):
        if path.endswith((".png", ".woff2")):
            continue
        text = body.decode()
        code = _outside_comments(text)
        found += [f"{path} names {v!r}" for v in values
                  if re.search(rf"(?<![\w.-]){re.escape(v)}(?![\w-])",
                               code if len(v) <= SHORT_VALUE else text)]
    from portfusion import secret_scan
    secrets, _, _ = secret_scan.credential_values([schema.BOOK])
    for path, body in sorted(tree.items()):
        found += [f"{where} {why}" for where, why in secret_scan.matches(path, body, secrets)]
    return found


# =================================================================================================
# GIT AND THE TUNNEL
# =================================================================================================

def _git(where: pathlib.Path, *args: str) -> str:
    r = subprocess.run(["git", "-C", str(where), *args], capture_output=True, text=True)
    if r.returncode:
        raise Refused(f"git {' '.join(args)} in {where}: {r.stderr.strip()}")
    return r.stdout.strip()


def _on_clean_main(where: pathlib.Path, what: str) -> None:
    branch = _git(where, "symbolic-ref", "--short", "HEAD")
    if branch != "main":
        raise Refused(f"{what} is on {branch!r}, not main")
    if _git(where, "status", "--porcelain"):
        raise Refused(f"{what} has uncommitted changes")


def source(root: pathlib.Path | None = None) -> str:
    """The book's commit being published: its `main`, clean, and already on GitHub, so the figures
    the hosted desk serves are ones a pushed commit holds. Read from the book's own folder, never
    from where the app is installed."""
    root = root or schema.BOOK
    _on_clean_main(root, "the book")
    head = _git(root, "rev-parse", "HEAD")
    r = subprocess.run(["git", "-C", str(root), "merge-base", "--is-ancestor", head,
                        "origin/main"], capture_output=True)
    if r.returncode:
        raise Refused("the book's main is not pushed: git push origin main, then publish")
    return head


def tunnel_url(port: int, status: dict | None = None) -> str | None:
    """The public https address Tailscale Funnel serves `port` at, or None if it does not.

    Read from `tailscale funnel status --json`, the local daemon's own configuration: a host is
    published when Funnel is allowed on it and one of its handlers proxies to this port."""
    if status is None:
        cli = shutil.which("tailscale") or next(
            (p for p in TAILSCALE if pathlib.Path(p).exists()), None)
        if cli is None:
            return None
        # A DAEMON THAT DOES NOT ANSWER IS NO TUNNEL, refused as a missing tunnel is, never a
        # traceback.
        try:
            r = subprocess.run([cli, "funnel", "status", "--json"], capture_output=True,
                               text=True, timeout=5)
        except (subprocess.TimeoutExpired, OSError):
            return None
        try:
            status = json.loads(r.stdout or "{}")
        except ValueError:
            return None
    allowed = status.get("AllowFunnel") or {}
    for hostport, web in (status.get("Web") or {}).items():
        proxies = [h.get("Proxy", "") for h in (web.get("Handlers") or {}).values()]
        if allowed.get(hostport) and any(re.search(rf"(127\.0\.0\.1|localhost):{port}/?$", p)
                                         for p in proxies):
            host, _, p = hostport.rpartition(":")
            return f"https://{host}" + ("" if p == "443" else f":{p}")
    return None


# =================================================================================================
# PUBLISH, AND THE HEADER'S SIGNAL
# =================================================================================================

def _outside_what_it_must_not_touch(deploy: pathlib.Path) -> None:
    """A publish deletes every file in the clone it did not write, so the clone is never the book,
    the app, the checkout or the home folder, never inside the first three, and never holds any."""

    def within(a: pathlib.Path, b: pathlib.Path) -> bool:
        # samefile, not ==: a Mac's disk ignores case, so two spellings can name one folder.
        return any(p.exists() and b.exists() and p.samefile(b) for p in (a, *a.parents))

    deploy = deploy.expanduser().absolute()
    for name, where, inside in (("the book", schema.BOOK, True), ("the app", schema.APP, True),
                                ("the checkout", schema.ROOT, True),
                                ("the home folder", pathlib.Path.home(), False)):
        if where is not None and (within(where, deploy) or inside and within(deploy, where)):
            raise Refused(f"deploy_repo {deploy} is too close to {name} ({where})")


def published(deploy: pathlib.Path | None = None) -> dict | None:
    deploy = deploy or DEPLOY
    if deploy is None:
        return None
    path = deploy / "version.json"
    return json.loads(path.read_text()) if path.exists() else None


def publish(port: int = 8768, deploy: pathlib.Path | None = None,
            tunnel: str | None = None, commit: str | None = None) -> dict:
    """Write, check, commit and push. Returns what was published, or says there was nothing."""
    deploy = deploy or DEPLOY
    if deploy is None:
        raise Refused("the book's settings name no deploy_repo (store/settings.csv)")
    _outside_what_it_must_not_touch(deploy)
    commit = commit or source()
    if not (deploy / ".git").exists():
        raise Refused(f"no clone of the deploy repository at {deploy}")
    if _git(deploy, "ls-files") and not (deploy / "version.json").exists():
        raise Refused(f"{deploy} holds files and no version.json: not a clone a publish wrote")
    _on_clean_main(deploy, "the deploy repository")
    tunnel = tunnel or tunnel_url(port)
    if tunnel is None:
        raise Refused(f"the tunnel is off: no Tailscale Funnel serves port {port}")
    if auth.proxy_secret() is None:
        raise Refused(f"no proxy secret at {auth.PROXY_SECRET}: the door would refuse every "
                      f"request Netlify signs (docs/desk-app.md, The hosted desk)")
    tree = files(tunnel)
    found = leaks(tree)
    if found:
        raise Refused("the bundle would publish what it must not:\n  " + "\n  ".join(found))
    was = published(deploy)
    m = manifest(tree, commit)
    if was and was["files"] == m["files"]:
        return {"published": False, "version": was["version"], "detail": "nothing to publish"}

    for path in [p for p in deploy.rglob("*") if p.is_file() and ".git" not in
                 p.relative_to(deploy).parts and p.relative_to(deploy).as_posix() not in tree]:
        path.unlink()
    for name, body in tree.items():
        (deploy / name).parent.mkdir(parents=True, exist_ok=True)
        (deploy / name).write_bytes(body)
    (deploy / "version.json").write_text(json.dumps(m, indent=2) + "\n")

    _git(deploy, "add", "-A")
    _git(deploy, "commit", "-q", "-m",
         f"Publish desk version {m['version']}: {m['code']}, the book at {commit[:7]}")
    _git(deploy, "push", "-q", "origin", "main")
    month = _dt.date.today().replace(day=1).isoformat()
    count = len(_git(deploy, "log", f"--since={month}", "--format=%h").split())
    return {"published": True, "version": m["version"], "code": m["code"], "source": commit,
            "tunnel": tunnel,
            "this_month": count}


_tunnel_seen: dict = {"at": 0.0, "port": None, "url": None}


def status() -> dict | None:
    """The hosted desk as this Mac sees it, for the header. None when this process opened no
    remote door: a branch desk, or one started without --remote-port, is not hosting anything."""
    from portfusion.desk import remote
    if remote.PORT is None:
        return None
    now = time.time()
    if _tunnel_seen["port"] != remote.PORT or now - _tunnel_seen["at"] > TUNNEL_CACHE:
        try:
            url = tunnel_url(remote.PORT)
        except (OSError, subprocess.SubprocessError):
            url = None
        _tunnel_seen.update(at=now, port=remote.PORT, url=url)
    was = published()
    return {"tunnel": _tunnel_seen["url"] is not None,
            "published": was["version"] if was else None,
            "current": bundle.version()}


def main(port: int = 8768) -> int:
    try:
        got = publish(port)
    except Refused as e:
        log.info(f"\n  Not published: {e}\n")
        return 1
    if not got["published"]:
        log.info(f"\n  Nothing to publish: version {got['version']} is already live.\n")
        return 0
    log.info(f"\n  Published version {got['version']}: {got['code']}, the book at "
             f"{got['source'][:7]}.\n"
             f"  Netlify deploys it from {DEPLOY.name}'s main in a minute or two.\n"
             f"  Publishes this month: {got['this_month']}.\n")
    return 0
