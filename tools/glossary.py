"""
THE DERIVED HALF OF docs/glossary.md.

The half of the glossary that has a code home is generated from that code, and a test asserts
the checked-in file matches what the constants produce — a vocabulary document kept by hand
drifts.

AN INDEX, NEVER A SECOND TELLING. It emits NAMES, VALUES and WHERE THEY LIVE; what a word MEANS
stays where it is defined, and `test_record.py` refuses a second telling of STATEMENT_GRADE
or SOURCE_HIERARCHY anywhere.

What has no constant behind it — the practice equivalences, "as at" against "as of", the three
clocks — stays hand-written above the marker.

    python3 tools/glossary.py            print the generated block
    python3 tools/glossary.py --write    write it into docs/glossary.md between the markers
"""
from __future__ import annotations

import pathlib
import sys

from portfusion.log import log

HERE = pathlib.Path(__file__).resolve().parent.parent     # the checkout; this file is in tools/
GLOSSARY = HERE / "docs" / "glossary.md"

#: Markers, not "everything after this heading": a heading is prose and somebody will reword it.
BEGIN = "<!-- BEGIN DERIVED — generated by glossary.py; do not edit between the markers -->"
END = "<!-- END DERIVED -->"


def _figures() -> list[str]:
    """Every headline figure the engine registers, with its basis and its unit.

    `Book.HEADLINE` is the registry `tests/test_figures.py` holds both renderers to; listed
    here, a reader meets the page's words in one place without reading Python.
    """
    from portfusion.engine import Book
    out = ["| Figure | Basis | Unit | A dated page may quote it |", "|---|---|---|---|"]
    for label, spec in Book.HEADLINE.items():
        # THE LOADED BOOK'S DAY IS NOT A CONSTANT: the since-start label carries it, so the index
        # names the day rather than printing one book's.
        label = "Return since the day the record begins (MWR)" if label == Book.SINCE_START else label
        # `point_in_time` asks whether the figure HAS A VALUE AT A DATE. A quarterly report may
        # print one that does; one that does not is live-only — "YTD income" and the YTD return
        # are year-to-date by construction, and the rest are as-they-stand-now.
        dated = "yes" if spec["point_in_time"] else "**no — live only**"
        out.append(f"| {label} | `{spec['basis']}` | {spec['unit']} | {dated} |")
    return out


def _declared_vocabularies() -> list[str]:
    """Every closed vocabulary declared to the LOADER, from `schema.Field(enum=)`.

    A declared vocabulary fails on load naming the table, the row and the column. Everything else
    in this book is a convention enforced by review, which is why these are worth listing apart:
    they are the ones a hand-edited CSV cannot get past.
    """
    from portfusion.record import schema
    # One row per vocabulary, not per table: `type` and `quality` are each one list on three.
    tables: dict[tuple, list[str]] = {}
    for table in schema.TABLES.values():
        for field in table.fields:
            if field.enum:
                tables.setdefault((field.name, field.enum), []).append(table.name)
    rows = ["| Column | Values | Tables |", "|---|---|---|"]
    for (column, enum), names in tables.items():
        values = " · ".join(f"`{v}`" for v in enum)
        if set(enum) <= set(schema.TABLES):
            values = f"the {len(enum)} record tables"
        rows.append(f"| `{column}` | {values} | {' · '.join(f'`{n}`' for n in names)} |")
    return rows


def _record_vocabularies() -> list[str]:
    """The closed sets `record/rules.py` holds, listed beside the declared vocabularies."""
    from portfusion.record import rules as D
    out = ["| Vocabulary | Values | Declared in |", "|---|---|---|"]

    # CODE CONSTANTS ONLY: the account order and the carried marks are the LOADED BOOK's facts,
    # and a generated block that printed them would make the checked-in file wrong the moment
    # another book loads. A book's own facts are read on the desk, not in the glossary.
    out.append("| Evidence classes | "
               + " · ".join(f"`{e.key}`" for e in D.EVIDENCE_CLASSES)
               + " | `rules.EVIDENCE_CLASSES` |")
    out.append("| Income that reaches the RETURN | "
               + " · ".join(f"`{c}`" for c in sorted(D.POSITION_INCOME))
               + " | `rules.POSITION_INCOME` |")
    out.append("| Income that does NOT | "
               + " · ".join(f"`{c}`" for c in sorted(D.ACCOUNT_INCOME))
               + " | `rules.ACCOUNT_INCOME` |")

    return out


def _tables() -> list[str]:
    """Every table in the store and what it is for, the first sentence of the schema's `doc`, and
    each column beside the heading a reader meets it under: one name from store to page."""
    from portfusion.house.headings import store_heading
    from portfusion.record import schema
    out = ["| Table | What it holds | Columns, as the desk heads them |", "|---|---|---|"]
    for name in sorted(schema.TABLES):
        table = schema.TABLES[name]
        first = " ".join((table.doc or "").split()).split(". ")[0].rstrip(".")
        cols = []
        for f in table.fields:
            word = store_heading(name, f.name)
            cols.append(f"`{f.name}` {word}" if word else f"`{f.name}`")
        out.append(f"| `{name}.csv` | {first} | {' · '.join(cols)} |")
    return out


def generate() -> str:
    """The whole derived block, between its markers."""
    parts = [BEGIN, "",
             "## 9 · The record's own words, generated",
             "",
             "**Everything below this line is DERIVED from the `record/` modules,",
             "`house/headings.py` and `Book.HEADLINE` by `tools/glossary.py`, and",
             "`tests/test_record.py` asserts that the checked-in file matches what those constants",
             "produce.** It cannot drift. It is an INDEX — names, values and where they live. What a",
             "word MEANS stays where it is defined, and `test_record.py` refuses this block if it",
             "starts to define one.",
             "",
             "### Every registered headline figure", ""]
    parts += _figures()
    parts += ["", "### Vocabularies declared to the LOADER", "",
              "A value outside these fails **on load**, naming the table, the row and the column.",
              ""]
    parts += _declared_vocabularies()
    parts += ["", "### Vocabularies the record's rules hold", "",
              "Closed sets `record/rules.py` keeps beside the loader's. An account name is refused",
              "on load by the join to the register (`schema.REFERENCES`) and the income split is",
              "asserted on import; the rest are held by the suite.", ""]
    parts += _record_vocabularies()
    parts += ["", "### The store, table by table", ""]
    parts += _tables()
    parts += ["", END]
    return "\n".join(parts) + "\n"


def write() -> bool:
    """Put the block into `docs/glossary.md`. Returns whether the file changed.

    THE MARKERS MUST ALREADY BE THERE. This will not invent a place to put the block: where the
    generated half sits in the document is an editorial decision and not this script's to make.
    """
    text = GLOSSARY.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        raise SystemExit(
            f"docs/glossary.md has no generated block. Add these two lines where it belongs:\n\n"
            f"{BEGIN}\n{END}\n")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + generate().rstrip("\n") + tail
    if new == text:
        return False
    GLOSSARY.write_text(new, encoding="utf-8")
    return True


if __name__ == "__main__":
    if "--write" in sys.argv[1:]:
        log.info("docs/glossary.md updated" if write() else "docs/glossary.md already current")
    else:
        log.info(generate())
